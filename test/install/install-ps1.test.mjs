import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import {
  copyFileSync,
  linkSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { test } from "node:test";

// install.ps1 写的启动脚本 bin\orangespeakeasy.cmd。它照 current 找 versions 下的程序；从旧版本升上来、启动脚本变了时，
// 旧的那份可能正跑着（orangespeakeasy update 就是它起的）就被改写，cmd 等程序退出后从原来的字节位置接着读。
// 后两条要在 Windows 上真的起 cmd，"程序"是改名成 electron.exe 的 node。
// 最后两条把 install.ps1 里写定位文件、清旧版本的那几个函数原样拿出来，在 Windows PowerShell 里跑。

const INSTALLER = resolve(import.meta.dirname, "..", "..", "install.ps1");
const windowsOnly = { skip: process.platform !== "win32" && "要在 Windows 上起 cmd" };

/** 0.9.0–0.9.2 的 install.ps1 写的启动脚本，原样 */
const LEGACY_LAUNCHER = `${[
  "@echo off",
  "rem The orangespeakeasy command, generated by the OrangeSpeakEasy installer.",
  "rem Runs on the bundled Electron as Node, so Node does not need to be installed.",
  "setlocal",
  'if not defined ORANGESPEAKEASY_HOME for %%I in ("%~dp0..") do set "ORANGESPEAKEASY_HOME=%%~fI"',
  "set ELECTRON_RUN_AS_NODE=1",
  '"%~dp0..\\runtime\\electron.exe" "%~dp0..\\app\\bin\\orangespeakeasy.mjs" %*',
].join("\r\n")}\r\n`;

/** 0.9.3 起的 install.ps1 写的启动脚本，原样。发出去了就不再改：以后的版本从它这里升级时，它也可能正跑着 */
const LAUNCHER_0_9_3 = `${[
  "@echo off",
  "setlocal",
  'if not defined ORANGESPEAKEASY_HOME for %%I in ("%~dp0..") do set "ORANGESPEAKEASY_HOME=%%~fI"',
  'set /p ORANGESPEAKEASY_CURRENT=<"%~dp0..\\current"',
  "set ELECTRON_RUN_AS_NODE=1",
  '"%~dp0..\\versions\\%ORANGESPEAKEASY_CURRENT%\\runtime\\electron.exe" "%~dp0..\\versions\\%ORANGESPEAKEASY_CURRENT%\\app\\bin\\orangespeakeasy.mjs" %*',
].join("\r\n")}\r\n`;

/** 发出去过的每一版启动脚本。改了 install.ps1 里的启动脚本、发了版，就把新的那版加进来 */
const SHIPPED_LAUNCHERS = { "0.9.0–0.9.2": LEGACY_LAUNCHER, "0.9.3": LAUNCHER_0_9_3 };

/** 照 install.ps1 里 $LauncherText 那几行拼出它写进文件的内容：单引号字符串，'' 是一个 ' */
function launcher() {
  const source = readFileSync(INSTALLER, "utf8");
  const block = /\$LauncherText = @\(\r?\n([\s\S]*?)\r?\n\s*\) -join "`r`n"/.exec(source);
  assert.ok(block, "install.ps1 里找不到 $LauncherText");
  const lines = [...block[1].matchAll(/^\s*'((?:[^']|'')*)',?\s*$/gm)].map((match) => match[1].replaceAll("''", "'"));
  return `${lines.join("\r\n")}\r\n`;
}

/** 在 dir 里放一个"electron.exe"：其实是 node（硬链接，不同盘时复制） */
function fakeElectron(dir) {
  mkdirSync(dir, { recursive: true });
  const exe = join(dir, "electron.exe");
  try {
    linkSync(process.execPath, exe);
  } catch {
    copyFileSync(process.execPath, exe);
  }
}

function runCmd(file, args = []) {
  return spawnSync("cmd", ["/d", "/c", file, ...args], { encoding: "utf8", windowsHide: true });
}

test("启动脚本不比发出去过的任何一版长：旧的正跑着时被改写，cmd 接着读到的是文件末尾", () => {
  const text = launcher();
  for (const [version, shipped] of Object.entries(SHIPPED_LAUNCHERS)) {
    assert.ok(
      Buffer.byteLength(text) <= Buffer.byteLength(shipped),
      `新的 ${Buffer.byteLength(text)} 字节，${version} 的 ${Buffer.byteLength(shipped)} 字节`,
    );
  }
  assert.match(text, /set \/p ORANGESPEAKEASY_CURRENT=<"%~dp0\.\.\\current"/);
  assert.match(text, /"%~dp0\.\.\\versions\\%ORANGESPEAKEASY_CURRENT%\\runtime\\electron\.exe"/);
  assert.ok(text.endsWith("%*\r\n"), "调程序的那一行要是最后一行");
});

test("启动脚本照 current 起 versions 下的那个版本，参数原样带过去，家目录是它所在的那个", windowsOnly, (t) => {
  const home = mkdtempSync(join(tmpdir(), "sm-launcher-"));
  t.after(() => rmSync(home, { recursive: true, force: true }));
  const version = join(home, "versions", "0.1.0-1a2b3c4d");
  fakeElectron(join(version, "runtime"));
  mkdirSync(join(version, "app", "bin"), { recursive: true });
  writeFileSync(
    join(version, "app", "bin", "orangespeakeasy.mjs"),
    "console.log(JSON.stringify({ home: process.env.ORANGESPEAKEASY_HOME, args: process.argv.slice(2), node: process.env.ELECTRON_RUN_AS_NODE }));\n",
  );
  writeFileSync(join(home, "current"), "0.1.0-1a2b3c4d");
  mkdirSync(join(home, "bin"));
  writeFileSync(join(home, "bin", "orangespeakeasy.cmd"), launcher());

  const result = runCmd(join(home, "bin", "orangespeakeasy.cmd"), ["status", "--json"]);
  assert.equal(result.status, 0, result.stderr);
  assert.deepEqual(JSON.parse(result.stdout), { home, args: ["status", "--json"], node: "1" });
});

test(
  "0.9.2 的启动脚本正跑着时被改写成新的：程序退出后 cmd 读到文件末尾，正常结束；新的要是更长就会出错",
  windowsOnly,
  (t) => {
    const home = mkdtempSync(join(tmpdir(), "sm-launcher-"));
    t.after(() => rmSync(home, { recursive: true, force: true }));
    fakeElectron(join(home, "runtime"));
    mkdirSync(join(home, "app", "bin"), { recursive: true });
    mkdirSync(join(home, "bin"));
    const cmdFile = join(home, "bin", "orangespeakeasy.cmd");
    // 程序（像 orangespeakeasy update 跑的安装脚本那样）把正在跑它的启动脚本改写掉，再退出
    writeFileSync(
      join(home, "app", "bin", "orangespeakeasy.mjs"),
      `import { writeFileSync } from "node:fs";\nwriteFileSync(${JSON.stringify(cmdFile)}, process.env.NEXT_LAUNCHER);\nconsole.log("updated");\n`,
    );

    const rewrite = (next) => {
      writeFileSync(cmdFile, LEGACY_LAUNCHER);
      return spawnSync("cmd", ["/d", "/c", cmdFile], {
        encoding: "utf8",
        windowsHide: true,
        env: { ...process.env, NEXT_LAUNCHER: next },
      });
    };

    const ok = rewrite(launcher());
    assert.equal(ok.status, 0, ok.stderr);
    assert.equal(ok.stdout.trim(), "updated");
    assert.equal(ok.stderr, "");

    // 对照：新内容比旧的长时，cmd 从旧的长度处接着读，读到的是半截命令
    const longer = rewrite(`${launcher()}rem ${"x".repeat(80)}\r\necho should-not-run-from-the-middle\r\n`);
    assert.notEqual(`${longer.stdout}${longer.stderr}`.replace("updated", "").trim(), "");
  },
);

/** install.ps1 里一个函数的原文：一行写完的就是那一行，否则到下面第一个缩进两格的 "}" */
function functionText(name) {
  const source = readFileSync(INSTALLER, "utf8");
  const found = new RegExp(`^  function ${name}\\b[^\\n]*(?:\\}|\\{\\r?\\n[\\s\\S]*?^  \\})\\r?$`, "m").exec(source);
  assert.ok(found, `install.ps1 里找不到 ${name}`);
  return found[0];
}

test("定位文件已经在（搬家时记着 moving、换到别处）：改写成新位置，不留临时文件", windowsOnly, (t) => {
  const root = mkdtempSync(join(tmpdir(), "sm-loc-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const dir = join(root, "OrangeSpeakEasy");
  const file = join(dir, "location.json");
  mkdirSync(dir);
  writeFileSync(
    file,
    JSON.stringify({ home: "C:\\Old\\.orangespeakeasy", moving: { to: "D:\\New\\.orangespeakeasy", pid: 1 } }),
  );
  const script = join(root, "update-location.ps1");
  const body = [
    ...["Ok", "Note", "Fail", "Pretty", "Update-Location"].map(functionText),
    "$ErrorActionPreference = 'Stop'",
    `$script:LocationFile = '${file}'`,
    `$script:DefaultHome = '${join(root, ".orangespeakeasy")}'`,
    "$script:HomeDir = 'D:\\New\\.orangespeakeasy'",
    "Update-Location",
  ].join("\r\n");
  // 带 BOM：Windows PowerShell 5.1 才按 UTF-8 读（函数里有中文注释）
  writeFileSync(script, `\ufeff${body}\r\n`);
  const run = spawnSync(
    "powershell",
    ["-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-File", script],
    {
      encoding: "utf8",
      windowsHide: true,
    },
  );
  assert.equal(run.status, 0, `${run.stdout}${run.stderr}`);
  assert.deepEqual(JSON.parse(readFileSync(file, "utf8")), { home: "D:\\New\\.orangespeakeasy" });
  assert.deepEqual(readdirSync(dir), ["location.json"]);
});

// issue #11：5.1 里进程的 Path 每读一次都现算（$this.Mainmodule.FileName），进程退出后再读是空的。
// 这里把 Get-Process 换成"列完所有进程就停掉一个"，造出列进程和比路径之间有程序退出（比如刚停掉的旧版本）
test("清旧版本时有程序刚退出：不报错，没人用的旧版本照删、在用的这一版留着", windowsOnly, (t) => {
  const root = mkdtempSync(join(tmpdir(), "sm-old-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const home = join(root, ".orangespeakeasy");
  const old = join(home, "versions", "0.9.3-0123abcd");
  const current = join(home, "versions", "0.13.1-89abcdef");
  mkdirSync(old, { recursive: true });
  mkdirSync(current, { recursive: true });
  const pattern = /^ {2}\$VersionNamePattern = .*$/m.exec(readFileSync(INSTALLER, "utf8"));
  assert.ok(pattern, "install.ps1 里找不到 $VersionNamePattern");
  const script = join(root, "remove-old.ps1");
  const body = [
    ...["Ok", "Note", "Pretty", "Remove-Later", "Test-OtherUpdate", "Remove-Old"].map(functionText),
    "$ErrorActionPreference = 'Stop'",
    pattern[0],
    `$script:HomeDir = '${home}'`,
    `$script:VersionsDir = '${join(home, "versions")}'`,
    "$script:VersionName = '0.13.1-89abcdef'",
    "$script:PreviousName = ''; $script:InPlace = $false",
    "$victim = Start-Process -FilePath \"$env:WINDIR\\System32\\ping.exe\" -ArgumentList '-n', '30', '127.0.0.1' -WindowStyle Hidden -PassThru",
    "Start-Sleep -Milliseconds 500",
    "function Get-Process { Microsoft.PowerShell.Management\\Get-Process; Stop-Process -Id $victim.Id -Force; $victim.WaitForExit() }",
    "Remove-Old",
  ].join("\r\n");
  writeFileSync(script, `\ufeff${body}\r\n`);
  const run = spawnSync(
    "powershell",
    ["-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-File", script],
    { encoding: "utf8", windowsHide: true },
  );
  assert.equal(run.status, 0, `${run.stdout}${run.stderr}`);
  assert.deepEqual(readdirSync(join(home, "versions")), ["0.13.1-89abcdef"]);
});
